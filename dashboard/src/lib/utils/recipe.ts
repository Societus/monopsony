// Test an asset pattern against available assets
export function testAssetPattern(pattern: string, assets: string[]): { matches: string[]; misses: string[] } {
  if (!pattern) return { matches: [], misses: [...assets] };

  let regex: RegExp;
  try {
    regex = new RegExp(pattern);
  } catch {
    return { matches: [], misses: [...assets] };
  }

  const matches = assets.filter(a => regex.test(a));
  const misses = assets.filter(a => !regex.test(a));
  return { matches, misses };
}
