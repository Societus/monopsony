// Client-side recipe validation — fast checks that run before hitting the server.
// The server endpoint (/shadow/recipe/validate) is authoritative.

export interface ClientValidationResult {
  errors: { field: string; message: string }[];
  warnings: { field: string; message: string }[];
}

export function quickValidateToml(toml: string): ClientValidationResult {
  const errors: { field: string; message: string }[] = [];
  const warnings: { field: string; message: string }[] = [];

  if (!toml.trim()) {
    return { errors, warnings };
  }

  // Check for required sections
  const hasPackage = /^\[package\]/m.test(toml);
  const hasInstall = /^\[install\]/m.test(toml);
  const hasVersion = /^\[version\]/m.test(toml);

  if (!hasPackage) {
    errors.push({ field: 'package', message: 'Missing [package] section' });
  }
  if (!hasInstall) {
    errors.push({ field: 'install', message: 'Missing [install] section' });
  }
  if (!hasVersion) {
    errors.push({ field: 'version', message: 'Missing [version] section' });
  }

  // Check for required fields
  if (hasPackage) {
    if (!/^name\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'package.name', message: 'Package name not set' });
    }
    if (!/^source_type\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'package.source_type', message: 'Source type not set (github_release, git_build, or direct_url)' });
    }
    if (!/^source_url\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'package.source_url', message: 'Source URL not set' });
    }
  }

  if (hasInstall) {
    if (!/^method\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'install.method', message: 'Install method not set (extract, build, or script)' });
    }
    if (!/^target_dir\s*=\s*["']\/.+["']/m.test(toml)) {
      const targetMatch = toml.match(/^target_dir\s*=\s*["'](.*)["']/m);
      if (targetMatch && !targetMatch[1].startsWith('/')) {
        errors.push({ field: 'install.target_dir', message: `target_dir must be absolute path (got "${targetMatch[1]}")` });
      } else if (!targetMatch) {
        warnings.push({ field: 'install.target_dir', message: 'target_dir not set' });
      }
    }
  }

  if (hasVersion) {
    if (!/^detect_command\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'version.detect_command', message: 'Version detect command not set' });
    }
    if (!/^detect_pattern\s*=\s*["'].+["']/m.test(toml)) {
      warnings.push({ field: 'version.detect_pattern', message: 'Version detect pattern (regex) not set' });
    }
  }

  // Check regex validity for asset selector patterns
  const assetPatterns = [...toml.matchAll(/^pattern\s*=\s*["'](.+?)["']/gm)];
  for (let i = 0; i < assetPatterns.length; i++) {
    try {
      new RegExp(assetPatterns[i][1]);
    } catch {
      errors.push({
        field: `asset_selector.rules[${i}].pattern`,
        message: `Invalid regex: "${assetPatterns[i][1]}"`,
      });
    }
  }

  // Check version detect_pattern regex
  const versionPattern = toml.match(/^detect_pattern\s*=\s*["'](.+?)["']/m);
  if (versionPattern) {
    try {
      new RegExp(versionPattern[1]);
    } catch {
      errors.push({
        field: 'version.detect_pattern',
        message: `Invalid regex: "${versionPattern[1]}"`,
      });
    }
  }

  // Check tag_pattern regex
  const tagPattern = toml.match(/^tag_pattern\s*=\s*["'](.+?)["']/m);
  if (tagPattern) {
    try {
      new RegExp(tagPattern[1]);
    } catch {
      errors.push({
        field: 'asset_selector.tag_pattern',
        message: `Invalid regex: "${tagPattern[1]}"`,
      });
    }
  }

  return { errors, warnings };
}

